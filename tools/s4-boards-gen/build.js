// node tools/s4-boards-gen/build.js [outfile]  -> writes css/s4-scenes.css (the six Series 4 "Moonwick" boards).
// The scenes are SVG art written as code (lib.js has the helpers; one file per board draws its pieces and returns its CSS); the output is
// plain CSS with the SVGs as data URIs, so the game itself needs no build step. Edit a board here and run this to regenerate.
const fs = require('fs');
const path = require('path');
const OUT = process.argv[2] || path.resolve(__dirname, '..', '..', 'css', 's4-scenes.css');
const CLS = { library: 'board-library', glade: 'board-glade', alchemy: 'board-alchemy', observatory: 'board-observatory', isles: 'board-isles', tower: 'board-tower' };
const mods = Object.keys(CLS).filter((m) => fs.existsSync(path.join(__dirname, m + '.js')));
const ALL = mods.map((m) => '.' + CLS[m]);
const is = (list) => ':is(' + list.join(', ') + ')';
const ISALL = is(ALL);
const PREV = ':is(.bdg-scene, .hero-board, .mini-board)';

const head = `/* ===================================================================
   Series 4 "Moonwick" boards: Grand Library, Moonlit Glade, Alchemy Lab, Observatory, Floating Isles, Moonwick Tower
   (docs/update-5/series-4-moonwick.md, section 3.3). Same conventions as css/u4-boards.css: a board defines --a-bg (the whole static
   scene: what badges, previews, the reveal card, low-end phones and Reduce Motion show), --a-board, --a-frame and --a-glow. In a run the
   scene is split: --a-bg-run holds the parts that never move, and at most TWO continuous loops (.bg::before, .bg::after or the two
   .scene-fx layers) animate on top, on transform and opacity only. A board's moments (js/s4-scenes.js) are short transforms and
   opacity changes on a few layers that sit exactly on their static twins. Nothing here animates a layout property, a filter or a
   blend mode. Everything moving stops in html.low-end and html.reduced.
   Art is placed from the board's own variables, so the same picture works in a run (the centred HUD column: --s4-cw is --bw) and in
   a badge, the reveal or a preview (--s4-cw is the box). Generated by tools/s4-boards-gen from SVG art written as code.
   =================================================================== */

/* the floating ghost bricks and the blurred blobs would sit on top of a drawn scene */
${ISALL} .run-active :is(.blob, .bg-bricks) { display: none; }
${ISALL} .run-active .bg .vignette { opacity: 0.5; }
/* every moving layer is an overlay: it never takes a tap and never leaves its box. They start off; each board switches on the ones it uses. */
${ISALL} .run-active .bg::before, ${ISALL} .run-active .bg::after { content: ''; position: absolute; inset: auto; background: none; pointer-events: none; display: none; }
${ISALL} .run-active .bg .scene-fx { display: none; }
${PREV}:is(${ALL.join(', ')}) .scene-fx { display: none; }
/* the layers a board's moments use (js/s4-scenes.js makes them while the board is equipped): only in a run */
.bg .s4x { position: absolute; display: none; pointer-events: none; }
${ISALL} .run-active .bg .s4x { display: block; }

/* band sizes in a run: the art takes the free room above the pause row and below the message band (the run column is centred, so the
   two are about equal: --s4-free) plus a little overlap, and grows on tall phones. The bottom band never reaches up behind the
   power-up slots. */
${ISALL} {
  --s4-free: calc((100dvh - var(--bw) - 372px) / 2);
  --s4-th: clamp(56px, calc(var(--s4-free) + 30px), 100px);
  --s4-bh: clamp(72px, calc(var(--s4-free) + 56px), 128px);
  --s4-cx: 50%; --s4-cw: var(--bw);
}
/* in badges, previews and the reveal the bands grow so the scene still reads around the little board, and the art spreads over the box */
${PREV}:is(${ALL.join(', ')}) { --s4-th: 28%; --s4-bh: 36%; --s4-free: 20%; --s4-cx: 50%; --s4-cw: 100%; }
.mini-board:is(${ALL.join(', ')}) { --s4-th: 32%; --s4-bh: 40%; }

/* a soft dark plate behind the score (top right of the run column) and behind the message band: part of the run background so low-end
   phones get them too, and the score text keeps a shadow so it reads over any scene */
${ISALL} { --s4-hud: radial-gradient(ellipse 132px 60px at calc(50% + var(--bw) / 2 - 56px) calc(var(--s4-free) + 24px), var(--s4-plate) 0, var(--s4-plate) 24%, transparent 100%); }
${ISALL} .run-active .bg { background: var(--s4-hud), var(--a-bg-run); }
${ISALL} .run-active .msgband::before { content: ''; position: absolute; inset: -4px -22px; z-index: 0; pointer-events: none; opacity: 0; transition: opacity 0.2s; background: radial-gradient(ellipse closest-side at 50% 50%, var(--s4-plate) 0, var(--s4-plate) 60%, transparent 100%); }
${ISALL} .run-active .msgband:is([data-top="spark"], [data-top="aim"], [data-top="hint"], [data-top="combo"], [data-top="goal"])::before { opacity: 1; }
${ISALL} .run-active .score-box .lbl { color: #e8eeff; text-shadow: 0 1px 2px var(--s4-ink), 0 0 6px var(--s4-ink); }
${ISALL} .run-active .score-box b { text-shadow: 0 1px 3px var(--s4-ink), 0 0 8px var(--s4-ink); }

@keyframes s4Rise { to { transform: translate3d(0, -520px, 0); } }
@keyframes s4Bob { from { transform: translate3d(0, 3px, 0) rotate(-3deg); } to { transform: translate3d(0, -4px, 0) rotate(2.5deg); } }
@keyframes s4Glow { from { opacity: 0.35; } to { opacity: 1; } }
@keyframes s4Stars { to { transform: translate3d(-260px, 0, 0); } }
@keyframes s4Orbit { from { transform: scaleY(0.5) rotate(0deg); } to { transform: scaleY(0.5) rotate(360deg); } }
@keyframes s4Sea { to { transform: translate3d(calc(var(--s4-sea) * -8.667), 0, 0); } }
@keyframes s4Bob2 { from { transform: translate3d(0, 3px, 0); } to { transform: translate3d(0, -5px, 0); } }
@keyframes s4Clouds { to { transform: translate3d(-520px, 0, 0); } }
@keyframes s4Flicker { 0%, 100% { opacity: 1; } 35% { opacity: 0.45; } 60% { opacity: 0.85; } 80% { opacity: 0.35; } }
@keyframes s4Drift { to { transform: translate3d(-520px, 0, 0); } }
@keyframes s4Twinkle { 0%, 100% { opacity: 0.35; } 50% { opacity: 1; } }
@keyframes s4Wander { 0% { transform: translate3d(0, 0, 0); } 50% { transform: translate3d(34px, -260px, 0); } 100% { transform: translate3d(0, -520px, 0); } }

`;
const tail = `
/* small phones: the run column is tighter (see css/run.css), so the free room is measured with its numbers */
@media (max-height: 720px) and (orientation: portrait) {
  ${ISALL} { --s4-free: calc((100dvh - var(--bw) - 294px) / 2); --s4-bh: clamp(56px, calc(var(--s4-free) + 42px), 128px); }
}
/* tablets and desktop: the column stays in the middle and the art spreads along the whole width, so the bands follow the screen height */
@media (min-width: 701px) and (min-height: 561px) {
  ${ISALL} { --s4-th: min(96px, 12dvh); --s4-bh: min(128px, 15dvh); }
}
/* short landscape screens (a phone on its side): the board sits left, the HUD column right; the bands stay thin */
@media (orientation: landscape) and (max-height: 560px) {
  ${ISALL} { --s4-th: min(56px, 14%); --s4-bh: min(92px, 23%); --s4-cx: calc(50% - 158px); }
  ${ISALL} { --s4-hud: radial-gradient(ellipse 132px 60px at calc(50% + (var(--bw) + 316px) / 2 - 56px) 28px, var(--s4-plate) 0, var(--s4-plate) 24%, transparent 100%); }
}
/* low-end phones and reduced motion: the whole scene holds still on the static --a-bg */
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .run-active .bg { background: var(--s4-hud), var(--a-bg); }
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .run-active .bg::before,
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .run-active .bg::after,
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .run-active .bg .scene-fx,
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .run-active .bg .s4x { display: none; }
`;

let css = head;
for (const m of mods) {
  const r = require('./' + m).css();
  const cls = CLS[m];
  const [pr, pg, pb, pa] = r.plate;
  css += `/* ================================================================ ${m} */\n.${cls} {\n  --s4-plate: rgba(${pr}, ${pg}, ${pb}, ${pa}); --s4-ink: rgba(${pr}, ${pg}, ${pb}, 0.92);${r.vars}\n}\n${r.run || ''}${r.frame || ''}${r.media || ''}\n`;
}
css += tail;
css += require('./badges').css(mods);
fs.writeFileSync(OUT, css);
console.log('wrote', OUT, css.length, 'bytes', mods.join(','));
