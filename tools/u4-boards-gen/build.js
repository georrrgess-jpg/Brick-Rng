// node tools/u4-boards-gen/build.js [outfile]  -> writes css/u4-boards.css (the eight older boards, Update 4 touch-up).
// The scenes are SVG art written as code (lib.js has the helpers, one file per board draws its top band, bottom band and animated pieces);
// the output is plain CSS with the SVGs as data URIs, so the game itself needs no build step. Edit a board here and run this to regenerate.
const fs = require('fs');
const path = require('path');
const OUT = process.argv[2] || path.resolve(__dirname, '..', '..', 'css', 'u4-boards.css');
const mods = ['classic', 'deepsea', 'foundry', 'market', 'orbit', 'greenhouse', 'storm', 'holo'].filter((m) => fs.existsSync(path.join(__dirname, m + '.js')));
const CLS = { classic: 'board-classic', deepsea: 'board-deepsea', foundry: 'board-foundry', market: 'board-market', orbit: 'board-orbit', greenhouse: 'board-greenhouse', storm: 'board-storm', holo: 'board-holo' };
const ALL = Object.values(CLS).map((c) => '.' + c);
const is = (list) => ':is(' + list.join(', ') + ')';

const head = `/* ===================================================================
   Update 4: the eight older boards as illustrated scenes (Midnight, Deep Sea, Foundry, Night Market, Orbit, Greenhouse, Thunderhead,
   Hologrid). Same conventions as css/s3-scenes.css: a board defines --a-bg (the whole static scene: what badges, previews, the
   reveal card and low-end phones show), --a-board, --a-frame and --a-glow. In the run the scene is split: --a-bg-run holds the parts
   that never move, and up to TWO slow transform or opacity loops (.bg::before, .bg::after or the .scene-fx layers) sit on top.
   Every scene is a top band and a bottom band (repeat-x tiles, sized from the box so they work from a 56px badge to a desktop)
   plus a few focal pieces. Nothing here animates a layout property, a filter or a blend mode. Everything moving stops in
   html.low-end and html.reduced, and the static --a-bg takes over.
   Generated by a script from SVG art; the shapes are readable in the data URIs if one ever needs to be touched.
   =================================================================== */

/* the floating ghost bricks and the blurred blobs would sit on top of a drawn scene; the generic corner glow is part of the old look */
${is(ALL)} .run-active :is(.blob, .bg-bricks) { display: none; }
${is(ALL)} .run-active .bg .vignette { opacity: 0.5; }
${is(ALL)} .run-active .bg::before, ${is(ALL)} .run-active .bg::after { content: ''; position: absolute; inset: auto; background: none; pointer-events: none; }
${is(ALL)} .run-active .bg::before, ${is(ALL)} .run-active .bg::after { display: none; }
${is(ALL)} .run-active .bg .scene-fx { display: none; }
:is(.bdg-scene, .hero-board, .mini-board):is(${ALL.join(', ')}) .scene-fx { display: none; }

/* in badges, previews and the reveal the bands grow so the scene still reads around the little board */
:is(.bdg-scene, .hero-board, .mini-board):is(${ALL.join(', ')}) { --u4-th: 28%; --u4-bh: 36%; }
.mini-board:is(${ALL.join(', ')}) { --u4-th: 32%; --u4-bh: 40%; }

@keyframes u4Rise { to { transform: translate3d(0, -520px, 0); } }
@keyframes u4Sway { from { transform: skewX(-1.6deg); } to { transform: skewX(1.6deg); } }
@keyframes u4Swing { from { transform: rotate(-1.4deg); } to { transform: rotate(1.4deg); } }
@keyframes u4Orbit { from { transform: translate3d(-90px, 0, 0) rotate(-6deg); } to { transform: translate3d(calc(100vw + 30px), 10px, 0) rotate(6deg); } }
@keyframes u4Sheet { 0%, 100% { opacity: 0; } 3% { opacity: 0.95; } 4.5% { opacity: 0.15; } 6.5% { opacity: 0.7; } 11% { opacity: 0; } 55% { opacity: 0; } 57% { opacity: 0.55; } 60% { opacity: 0; } }
@keyframes u4Rain { to { transform: translate3d(0, 200px, 0); } }
@keyframes u4Drift { to { transform: translate3d(-480px, 0, 0); } }
@keyframes u4Pulse { from { opacity: 0.45; } to { opacity: 1; } }
@keyframes u4Twinkle { 0%, 100% { opacity: 0.35; } 50% { opacity: 1; } }

`;
const tail = `
/* small phones (640 tall): the bands shrink a little so the art does not sit behind the power-up slots */
@media (max-height: 700px) {
  :is(.board-classic, .board-foundry, .board-market, .board-orbit, .board-storm, .board-deepsea, .board-greenhouse) { --u4-th: min(112px, 13%); --u4-bh: min(176px, 20%); }
  .board-holo { --u4-th: min(112px, 13%); --u4-bh: min(116px, 15%); }
}
/* short landscape screens (a phone on its side): the bands shrink so they never crowd the HUD */
@media (max-height: 520px) {
  .board-classic, .board-foundry, .board-market, .board-orbit, .board-storm { --u4-th: min(112px, 12%); --u4-bh: min(176px, 19%); }
  .board-deepsea, .board-greenhouse { --u4-th: min(112px, 12%); --u4-bh: min(184px, 20%); }
  .board-holo { --u4-th: min(112px, 12%); --u4-bh: min(116px, 14%); }
}
/* low-end phones and reduced motion: the whole scene holds still on the static --a-bg */
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .run-active .bg { background: var(--a-bg); }
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .run-active .bg::before,
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .run-active .bg::after,
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .run-active .bg .scene-fx { display: none; }
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .board::before,
html:is(.low-end, .reduced):is(${ALL.join(', ')}) .board::after { animation: none !important; }
`;
let css = head;
for (const m of mods) css += require('./' + m)() + '\n';
css += tail;
fs.writeFileSync(OUT, css);
console.log('wrote', OUT, css.length, 'bytes', mods.join(','));
