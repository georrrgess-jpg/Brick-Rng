const { launch } = require('./lib');
const OUT = process.argv[2];
(async () => {
  const { browser, page, errors } = await launch({ width: 1280, height: 800, mobile: false });
  await page.evaluate(() => {
    BR.ITEMS.forEach((it, i) => BR.Progress.keep({ itemId: it.id, finish: ['matte', 'gloss', 'holo', 'prism'][i % 4], seed: i * 733 % 10000, tracker: null }));
    BR.Storage.data.profile.xp = 300; BR.Storage.data.profile.shards = 120;
    const P = BR.Progress, v = BR.Storage.data.profile.vault;
    P.equip(v.find((i) => i.itemId === 'f_lava').uid); P.equip(v.find((i) => i.itemId === 'a_market').uid); P.equip(v.find((i) => i.itemId === 'b_bolt').uid);
    BR.Skins.apply(); __brick.ui.refreshMenu();
  });
  await page.waitForTimeout(900);
  await page.screenshot({ path: OUT + '/d1-menu.png' });
  await page.click('#btnPlay');
  await page.waitForFunction(() => !__brick.busy, null, { timeout: 8000 });
  await page.evaluate(() => { __brick.store.data.seenTutorial = true; __brick.ui.hideHint(); __brick.view.hideHint(); __brick.engine.goal = 1e9; });
  await page.waitForTimeout(500);
  const q = await page.evaluate(() => { const a = __brick, g = a.engine.bestGroup(), p = g[Math.floor(g.length / 2)], c = a.view.pagePoint(p.r, p.c); return { x: c.x, y: c.y }; });
  await page.mouse.move(q.x, q.y); await page.waitForTimeout(300);
  await page.screenshot({ path: OUT + '/d2-game.png' });
  await page.mouse.down(); await page.mouse.up();
  await page.waitForTimeout(110);
  await page.screenshot({ path: OUT + '/d3-bolt.png', clip: { x: 340, y: 100, width: 600, height: 620 } });
  await page.waitForTimeout(1500);
  await page.click('#btnPause'); await page.waitForTimeout(500); await page.click('#btnQuit'); await page.waitForTimeout(500);
  await page.click('#btnVault'); await page.waitForTimeout(1200);
  await page.click('#vaultTabs button[data-tab="arena"]'); await page.waitForTimeout(900);
  await page.screenshot({ path: OUT + '/d4-vault.png' });
  console.log('errors', errors);
  await browser.close();
})();
