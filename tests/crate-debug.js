const { launch } = require('./lib');
const OUT = process.argv[2];
(async () => {
  const { browser, page, errors } = await launch({ width: 430, height: 820, mobile: false });
  await page.click('#btnPlay');
  await page.waitForTimeout(2200);
  await page.evaluate(() => { const e = window.__brick.engine; e.charge = e.need - 1; window.__brick.engine.rollCrate = () => BR.coreById.bomb; });
  const pt = await page.evaluate(() => { const a = window.__brick; const g = a.engine.bestGroup(); const p = g[0]; const q = a.view.pagePoint(p.r, p.c); return q; });
  await page.mouse.click(pt.x, pt.y);
  const log = async (tag) => console.log(tag, await page.evaluate(() => ({ inCrate: __brick.inCrate, crateShow: document.getElementById('crate').classList.contains('show'), stageOn: document.getElementById('crateStage').classList.contains('on'), reelOn: document.getElementById('reelStage').classList.contains('on'), resultOn: document.getElementById('result').classList.contains('on'), btnDisabled: document.getElementById('btnOpenCrate').disabled })));
  await page.waitForTimeout(2200); await log('t+2.2');
  await page.screenshot({ path: OUT + '/crate-1.png' });
  await page.click('#btnOpenCrate');
  await page.waitForTimeout(600); await page.screenshot({ path: OUT + '/crate-2.png' }); await log('open+.6');
  await page.waitForTimeout(1400); await page.screenshot({ path: OUT + '/crate-3.png' }); await log('open+2');
  await page.waitForTimeout(2500); await page.screenshot({ path: OUT + '/crate-4.png' }); await log('open+4.5');
  await page.waitForTimeout(3500); await log('open+8'); await page.screenshot({ path: OUT + '/crate-5.png' });
  await page.waitForTimeout(2500); await log('open+10.5'); await page.screenshot({ path: OUT + '/crate-6.png' });
  console.log(errors);
  await browser.close();
})();
